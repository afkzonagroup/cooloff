import { DEFAULT_LANGUAGE, isOfficialLanguage } from './i18n.js';
import type { OfficialLanguage } from './labels.js';
import { hasUnsafeCharacters, normaliseEmail, normaliseText } from './normalise.js';

/**
 * Length and count limits. The law sets none; these are implementation
 * choices that fit real names, order numbers and e-mail addresses
 * (RFC 5321 limits an address path to 254 characters).
 */
export const LIMITS = Object.freeze({
  nameMaxLength: 200,
  contractMaxLength: 100,
  emailMaxLength: 254,
  emailLocalMaxLength: 64,
  itemsMaxCount: 50,
  itemMaxLength: 200,
  idempotencyKeyMinLength: 16,
  idempotencyKeyMaxLength: 64,
});

/**
 * The online withdrawal statement of Article 11a(2) of Directive 2011/83/EU,
 * after validation and normalisation.
 */
export interface WithdrawalStatement {
  /** Art. 11a(2)(a): the consumer's name. */
  readonly name: string;
  /** Art. 11a(2)(b): details identifying the contract, e.g. an order number. */
  readonly contract: string;
  /** Art. 11a(2)(c): the electronic means for the acknowledgement: an e-mail address. */
  readonly email: string;
  /**
   * Optional partial withdrawal (recital 37 of Directive (EU) 2023/2673 allows
   * the trader to offer withdrawal from part of a contract). Empty = whole contract.
   */
  readonly items: readonly string[];
  /** Language the statement was made in. */
  readonly language: OfficialLanguage;
}

/** A validated request: the statement plus the client's idempotency key. */
export interface WithdrawalRequest extends WithdrawalStatement {
  /** Random key generated by the client for one form session. */
  readonly idempotencyKey: string;
}

/** Names of the fields a request may contain. */
export const REQUEST_FIELDS = Object.freeze([
  'name',
  'contract',
  'email',
  'items',
  'language',
  'idempotencyKey',
] as const);

/** A request field name. */
export type RequestField = (typeof REQUEST_FIELDS)[number];

/** Machine-readable validation error codes. */
export type ValidationErrorCode =
  | 'not_an_object'
  | 'unknown_field'
  | 'invalid_type'
  | 'required'
  | 'too_long'
  | 'invalid_email'
  | 'too_many_items'
  | 'item_too_long'
  | 'partial_not_allowed'
  | 'invalid_language'
  | 'invalid_idempotency_key';

/** One validation error. `field` is a request field, or `"_"` for the whole body. */
export interface ValidationError {
  readonly field: RequestField | '_';
  readonly code: ValidationErrorCode;
}

/** Result of {@link validateWithdrawalRequest}. */
export type ValidationResult =
  | { readonly ok: true; readonly value: WithdrawalRequest }
  | { readonly ok: false; readonly errors: readonly ValidationError[] };

/** Options for {@link validateWithdrawalRequest}. */
export interface ValidationOptions {
  /** Accept a list of items for partial withdrawal. Default `false`. */
  readonly allowPartial?: boolean;
  /** Language used when the request has none. Default `en`. */
  readonly defaultLanguage?: OfficialLanguage;
}

const FIELD_SET: ReadonlySet<string> = new Set(REQUEST_FIELDS);
const IDEMPOTENCY_KEY = /^[A-Za-z0-9_-]+$/u;
const EMAIL_LOCAL = /^[\p{L}\p{N}!#$%&'*+/=?^_`{|}~-]+(?:\.[\p{L}\p{N}!#$%&'*+/=?^_`{|}~-]+)*$/u;
const DOMAIN_LABEL = /^[\p{L}\p{N}](?:[\p{L}\p{N}-]{0,61}[\p{L}\p{N}])?$/u;

/**
 * Checks an e-mail address in the common `local@domain.tld` form.
 *
 * This deliberately accepts less than RFC 5322: no quoted local parts, no
 * comments, no IP-address literals, no single-label domains. Internationalised
 * letters are accepted. Line breaks and other control characters are never
 * accepted, which prevents e-mail header injection.
 */
export function isValidEmail(email: string): boolean {
  if (email.length === 0 || email.length > LIMITS.emailMaxLength) return false;
  if (hasUnsafeCharacters(email) || /\s/u.test(email)) return false;
  const at = email.lastIndexOf('@');
  if (at <= 0 || at !== email.indexOf('@')) return false;
  const local = email.slice(0, at);
  const domain = email.slice(at + 1);
  if (local.length > LIMITS.emailLocalMaxLength || !EMAIL_LOCAL.test(local)) return false;
  if (domain.length === 0 || domain.length > 253) return false;
  const labels = domain.split('.');
  if (labels.length < 2) return false;
  if (!labels.every((label) => DOMAIN_LABEL.test(label))) return false;
  const tld = labels[labels.length - 1] ?? '';
  return !/^\d+$/u.test(tld);
}

function isPlainObject(value: unknown): value is Record<string, unknown> {
  if (typeof value !== 'object' || value === null || Array.isArray(value)) return false;
  const proto: unknown = Object.getPrototypeOf(value);
  return proto === Object.prototype || proto === null;
}

function own(body: Record<string, unknown>, key: RequestField): unknown {
  return Object.hasOwn(body, key) ? body[key] : undefined;
}

function textField(
  body: Record<string, unknown>,
  field: 'name' | 'contract',
  maxLength: number,
  errors: ValidationError[],
): string {
  const raw = own(body, field);
  if (raw === undefined || raw === null) {
    errors.push({ field, code: 'required' });
    return '';
  }
  if (typeof raw !== 'string') {
    errors.push({ field, code: 'invalid_type' });
    return '';
  }
  // Cheap guard before normalising very large strings; the body limit caps them anyway.
  if (raw.length > maxLength * 4) {
    errors.push({ field, code: 'too_long' });
    return '';
  }
  const value = normaliseText(raw);
  if (value.length === 0) errors.push({ field, code: 'required' });
  else if (value.length > maxLength) errors.push({ field, code: 'too_long' });
  return value;
}

/**
 * Validates and normalises an untrusted request body (already parsed JSON).
 *
 * Rules:
 * - the body is a plain object with no fields other than {@link REQUEST_FIELDS};
 * - `name` (Art. 11a(2)(a)) and `contract` (Art. 11a(2)(b)) are required
 *   strings, normalised with {@link normaliseText}, at most
 *   {@link LIMITS} characters;
 * - `email` (Art. 11a(2)(c)) is a required, valid e-mail address;
 * - `items` is optional; only accepted when `allowPartial` is set;
 * - `language` is optional and must be an official EU language code;
 * - `idempotencyKey` is required, 16 to 64 characters of `A-Z a-z 0-9 _ -`.
 *
 * @example
 * ```ts
 * const result = validateWithdrawalRequest({
 *   name: 'Jane Doe', contract: 'ORDER-1001', email: 'jane@example.eu',
 *   idempotencyKey: 'k_0123456789abcdef',
 * });
 * if (result.ok) console.log(result.value.contract); // 'ORDER-1001'
 * ```
 */
export function validateWithdrawalRequest(body: unknown, options: ValidationOptions = {}): ValidationResult {
  if (!isPlainObject(body)) {
    return { ok: false, errors: [{ field: '_', code: 'not_an_object' }] };
  }
  const errors: ValidationError[] = [];
  for (const key of Object.keys(body)) {
    if (!FIELD_SET.has(key)) {
      errors.push({ field: '_', code: 'unknown_field' });
      break;
    }
  }

  const name = textField(body, 'name', LIMITS.nameMaxLength, errors);
  const contract = textField(body, 'contract', LIMITS.contractMaxLength, errors);

  let email = '';
  const rawEmail = own(body, 'email');
  if (rawEmail === undefined || rawEmail === null) errors.push({ field: 'email', code: 'required' });
  else if (typeof rawEmail !== 'string') errors.push({ field: 'email', code: 'invalid_type' });
  else {
    email = normaliseEmail(rawEmail.length > LIMITS.emailMaxLength * 4 ? '' : rawEmail);
    if (email.length === 0) errors.push({ field: 'email', code: rawEmail.trim().length === 0 ? 'required' : 'too_long' });
    else if (email.length > LIMITS.emailMaxLength) errors.push({ field: 'email', code: 'too_long' });
    else if (!isValidEmail(email)) errors.push({ field: 'email', code: 'invalid_email' });
  }

  const items: string[] = [];
  const rawItems = own(body, 'items');
  if (rawItems !== undefined && rawItems !== null) {
    if (!Array.isArray(rawItems)) errors.push({ field: 'items', code: 'invalid_type' });
    else if (rawItems.length > LIMITS.itemsMaxCount) errors.push({ field: 'items', code: 'too_many_items' });
    else {
      for (const item of rawItems as unknown[]) {
        if (typeof item !== 'string') {
          errors.push({ field: 'items', code: 'invalid_type' });
          break;
        }
        const value = item.length > LIMITS.itemMaxLength * 4 ? null : normaliseText(item);
        if (value === null || value.length > LIMITS.itemMaxLength) {
          errors.push({ field: 'items', code: 'item_too_long' });
          break;
        }
        if (value.length > 0) items.push(value);
      }
      if (items.length > 0 && options.allowPartial !== true) {
        errors.push({ field: 'items', code: 'partial_not_allowed' });
      }
    }
  }

  let language: OfficialLanguage = options.defaultLanguage ?? DEFAULT_LANGUAGE;
  const rawLanguage = own(body, 'language');
  if (rawLanguage !== undefined && rawLanguage !== null) {
    if (isOfficialLanguage(rawLanguage)) language = rawLanguage;
    else errors.push({ field: 'language', code: 'invalid_language' });
  }

  let idempotencyKey = '';
  const rawKey = own(body, 'idempotencyKey');
  if (
    typeof rawKey !== 'string' ||
    rawKey.length < LIMITS.idempotencyKeyMinLength ||
    rawKey.length > LIMITS.idempotencyKeyMaxLength ||
    !IDEMPOTENCY_KEY.test(rawKey)
  ) {
    errors.push({ field: 'idempotencyKey', code: 'invalid_idempotency_key' });
  } else {
    idempotencyKey = rawKey;
  }

  if (errors.length > 0) return { ok: false, errors };
  return {
    ok: true,
    value: Object.freeze({
      name,
      contract,
      email,
      items: Object.freeze(items),
      language,
      idempotencyKey,
    }),
  };
}
