import type { OfficialLanguage } from './labels.js';

/**
 * Interface strings that the law does not prescribe: form field labels, hints,
 * error messages and the acknowledgement e-mail.
 *
 * These are NOT taken from an official text. They are working translations
 * (`source: "translation"`) and need review by a native speaker before
 * production use. Traders can override any of them.
 *
 * Placeholders: `{email}` and `{receipt}`. They are replaced with plain string
 * operations; the result is always rendered as text, never as HTML.
 */
export interface Messages {
  /** Heading of the withdrawal form. */
  readonly formTitle: string;
  /** Short instruction above the form fields. */
  readonly formIntro: string;
  /** Label of the consumer name field (Art. 11a(2)(a)). */
  readonly nameLabel: string;
  /** Label of the contract identification field (Art. 11a(2)(b)). */
  readonly contractLabel: string;
  /** Label of the e-mail field (Art. 11a(2)(c)). */
  readonly emailLabel: string;
  /** Hint under the e-mail field. */
  readonly emailHint: string;
  /** Label of the optional partial-withdrawal field (recital 37). */
  readonly itemsLabel: string;
  /** Hint under the partial-withdrawal field. */
  readonly itemsHint: string;
  /** Short label for the items in the acknowledgement. */
  readonly itemsField: string;
  /** Cancel button. */
  readonly cancel: string;
  /** Close button after success. */
  readonly close: string;
  /** Status text while the statement is being sent. */
  readonly sending: string;
  /** Field error: empty. */
  readonly errorRequired: string;
  /** Field error: too long. */
  readonly errorTooLong: string;
  /** Field error: not an e-mail address. */
  readonly errorEmail: string;
  /** Field error: too many items or an item too long. */
  readonly errorItems: string;
  /** Form-level error when fields are invalid. */
  readonly errorSummary: string;
  /** Form-level error when sending failed. */
  readonly errorSend: string;
  /** Form-level error when the server rate-limited the request. */
  readonly errorRateLimited: string;
  /** Heading after a successful submission. */
  readonly successTitle: string;
  /** Label of the receipt number. */
  readonly receiptLabel: string;
  /** Label of the date and time of submission (Art. 11a(4)). */
  readonly submittedAtLabel: string;
  /** Text after success when the acknowledgement was sent. Uses `{email}`. */
  readonly ackSent: string;
  /** Text after success when the acknowledgement is queued. Uses `{email}`. */
  readonly ackPending: string;
  /** Subject of the acknowledgement e-mail. Uses `{receipt}`. */
  readonly emailSubject: string;
  /** First paragraph of the acknowledgement e-mail. */
  readonly emailIntro: string;
  /** The withdrawal statement sentence included in the acknowledgement. */
  readonly statementText: string;
  /** Label for the trader name in the acknowledgement. */
  readonly traderLabel: string;
  /** Value shown when the consumer withdraws from the whole contract. */
  readonly wholeContract: string;
}

/** One language's interface strings with their provenance. */
export interface MessageCatalogue {
  readonly language: OfficialLanguage;
  /** Always `"translation"`: not taken from an official text. */
  readonly source: 'translation';
  readonly messages: Messages;
}

